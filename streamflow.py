array4 = np.genfromtxt('/content/2012-US-Birth-Rates.csv', delimiter=',', dtype=str, skip_header=1)
x = array4[:, 0].astype('datetime64')
y_1 = array4[:, 1].astype(float)

"""### Graphing the Data

Plot x and y_1 with the elements shown in the instructions in the code block below.
"""

plt.figure(figsize=(15, 6))
plt.plot(x, y_1, color='#3182bd', alpha=0.85)

# Used AI to create the curved arrows

holidays = {
    "New Year's Day": ('2012-01-01', 4000, (30, -20)),
    "4th of July": ('2012-07-04', 4330, (30, -20)),
    "Halloween": ('2012-10-31', 4680, (-80, -20)),
    "Thanksgiving": ('2012-11-27', 4500, (-80, -40)),
    "Christmas": ('2012-12-25', 3840, (-120, 20))
}

for name, (date_str, y_val, offset) in holidays.items():
    target_date = np.datetime64(date_str)

    # Use a straight arrow for New Year's Day, and a curved arrow (arc3) for the other holidays
    if name == "New Year's Day":
        arrow_props = dict(arrowstyle="->", color='black', lw=3)
    else:
        arrow_props = dict(arrowstyle="->", color='black', lw=3, connectionstyle="arc3,rad=-0.2")

    plt.annotate(
        name,
        xy=(target_date, y_val),
        xytext=(offset[0], offset[1]),
        textcoords='offset points',
        arrowprops=arrow_props,
        fontsize=10,
        fontweight='bold',
        color='black'
    )

plt.xlabel('Date', fontsize=10)
plt.ylabel('Births', fontsize=10)
plt.title('Average U.S. Daily Birth Data', fontsize=12)
plt.grid(True)
plt.show()

