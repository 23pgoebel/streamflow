"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

from types import resolve_bases
L = 6
R_A = 170
R_B = 410
P1 = 100
q1 = 120
q2 = 120

x = np.linspace(0,L,500)
v = np.zeros_like(x)

# AI helped me come up with the range(len(x)) combo

for i in range(len(x)):
  if x[i] < 2:
    V = R_A - (q1*x[i])
  elif x[i] < 4:
    V = R_A - (q1*2) - P1
  else:
    V = R_A - (q1*2) - P1 + R_B - (q2*(x[i]-4))

  v[i] = V

# AI helped me plot the x axis line.

plt.plot(x,v)
plt.axhline(0, color='black', linewidth=1.2, linestyle='-')
plt.xlabel('x (ft)')
plt.ylabel('V (lb)')
plt.title('Shear Diagram')
plt.fill_between(x,v,color='blue', alpha = .1)
plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

L = 6
R_A = 170
R_B = 410
P1 = 100
q1 = 120
q2 = 120

x = np.linspace(0,L,500)
M = np.zeros_like(x)

# Copy and pased if elif statement from above then modified it to match

for i in range(len(x)):
  if x[i] < 2:
    m = R_A*x[i] - (q1*(x[i]**2))/2
  elif x[i] < 4:
    m = R_A*x[i] - (q1*2)*(x[i]-1) - (P1*(x[i]-2))
  else:
    m = R_A*x[i] - (q1*2)*(x[i]-1) - P1*(x[i]-2) + R_B*(x[i]-4) - (q2*(x[i]-4)*(x[i]-4)/2)

  M[i] = m

plt.plot(x,M)
plt.axhline(0, color='black', linewidth=1.2, linestyle='-')
plt.xlabel('x (ft)')
plt.ylabel('M (lb-ft)')
plt.title('Moment Diagram')
plt.fill_between(x,M,color='blue', alpha = .1)
plt.show()

